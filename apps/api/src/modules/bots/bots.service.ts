import { BadRequestException, Injectable, Logger, NotFoundException } from '@nestjs/common';
import { Prisma } from '@prisma/client';
import {
  BOT_MAX_PER_OWNER,
  BOT_NAME_MIN_LENGTH,
  type BotSecret,
  type CreateBotResult,
  type OwnedBot,
} from '@discord-clone/shared';
import { hashSecretToken } from '@/common/secret-token';
import { PrismaService } from '@/modules/prisma/prisma.service';
import { RealtimePublisher } from '@/modules/realtime/realtime-publisher.service';
import { BotAuthorizationService } from './bot-authorization.service';
import { deleteBotWithMemberships } from './bot-memberships';
import { botUserIdentity, issueBotToken } from './bot-token';
import { CreateBotDto } from './dto/create-bot.dto';

const ownedBotSelect = {
  id: true,
  name: true,
  avatarUrl: true,
  createdAt: true,
  botUser: { select: { _count: { select: { memberships: true } } } },
} satisfies Prisma.BotSelect;

type OwnedBotRow = Prisma.BotGetPayload<{ select: typeof ownedBotSelect }>;

function toOwnedBot({ botUser, ...bot }: OwnedBotRow): OwnedBot {
  return { ...bot, serverCount: botUser._count.memberships };
}

/**
 * A person's own bots. Every action is scoped to `ownerId`, so another user's bot reads as not found.
 * The plaintext token leaves this service only in the create and regenerate responses.
 */
@Injectable()
export class BotsService {
  private readonly logger = new Logger(BotsService.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly authorization: BotAuthorizationService,
    private readonly realtime: RealtimePublisher,
  ) {}

  async list(userId: string): Promise<{ bots: OwnedBot[] }> {
    const bots = await this.prisma.bot.findMany({
      where: { ownerId: userId },
      select: ownedBotSelect,
      orderBy: { createdAt: 'asc' },
    });
    return { bots: bots.map(toOwnedBot) };
  }

  async create(userId: string, dto: CreateBotDto): Promise<CreateBotResult> {
    const name = dto.name.trim();
    if (name.length < BOT_NAME_MIN_LENGTH) throw new BadRequestException('Bot name is too short');
    const count = await this.prisma.bot.count({ where: { ownerId: userId } });
    if (count >= BOT_MAX_PER_OWNER) throw new BadRequestException('Bot limit reached');

    // Hashed before the transaction: bcrypt is slow and must not hold the connection.
    const identity = await botUserIdentity();
    const avatarUrl = dto.avatarUrl ?? null;
    const { bot, token } = await this.prisma.$transaction(async (tx) => {
      const botUser = await tx.user.create({
        data: { ...identity, kind: 'BOT', displayName: name, avatarUrl },
        select: { id: true },
      });
      // The token embeds the id, so the row is created first and its hash stored right after.
      const created = await tx.bot.create({
        data: { ownerId: userId, botUserId: botUser.id, name, avatarUrl, tokenHash: '' },
        select: { id: true },
      });
      const issued = issueBotToken(created.id);
      const stored = await tx.bot.update({
        where: { id: created.id },
        data: { tokenHash: hashSecretToken(issued.secret) },
        select: ownedBotSelect,
      });
      return { bot: stored, token: issued.token };
    });

    // A bot belongs to no server yet, so there is no server audit log to write; this is the record.
    this.logger.log(`Bot ${bot.id} created by user ${userId}`);
    return { bot: toOwnedBot(bot), token };
  }

  /** The old token stops matching as soon as the new hash is stored; there is no overlap window. */
  async regenerateToken(userId: string, botId: string): Promise<BotSecret> {
    const bot = await this.requireOwnedBot(userId, botId);
    const issued = issueBotToken(bot.id);
    const memberships = await this.prisma.serverMember.findMany({
      where: { userId: bot.botUserId },
      select: { serverId: true },
    });
    await this.prisma.$transaction([
      this.prisma.bot.update({
        where: { id: bot.id },
        data: { tokenHash: hashSecretToken(issued.secret) },
      }),
      // Audited in every server the bot can act in, since those are the servers the old token reached.
      this.prisma.auditLog.createMany({
        data: memberships.map(({ serverId }) => ({
          serverId,
          actorId: userId,
          action: 'BOT_TOKEN_REGENERATE',
          targetId: bot.id,
          metadata: { botId: bot.id },
        })),
      }),
    ]);
    // The old token stops working for the gateway the same way it already does for `/bot-api/*`; the
    // bot process must reconnect with the new one (Gateway → Disconnect).
    this.realtime.disconnectBotSocket(bot.id);
    this.logger.log(`Bot ${bot.id} token regenerated by user ${userId}`);
    return { token: issued.token };
  }

  /**
   * Revokes the token and every membership at once. The bot's User row stays, so messages it already
   * posted keep their author.
   */
  async remove(userId: string, botId: string) {
    const bot = await this.requireOwnedBot(userId, botId);
    const removedFrom = await this.prisma.$transaction((tx) =>
      deleteBotWithMemberships(tx, bot, userId),
    );
    this.authorization.announceRemoval(bot.botUserId, removedFrom);
    // The Bot row is already gone, so `announceRemoval`'s own bot lookup misses; disconnect directly.
    this.realtime.disconnectBotSocket(bot.id);
    this.logger.log(`Bot ${bot.id} deleted by user ${userId}`);
    return { ok: true };
  }

  private async requireOwnedBot(userId: string, botId: string) {
    const bot = await this.prisma.bot.findFirst({
      where: { id: botId, ownerId: userId },
      select: { id: true, name: true, botUserId: true },
    });
    if (!bot) throw new NotFoundException('Bot not found');
    return bot;
  }
}
